// Writes the seed migration for the places map's Listed tier from src/lib/listedPlaces.ts, so the
// database and the app's built-in fallback list hold the same places.
//
//   node scripts/listed-places-sql.mjs supabase/migrations/<timestamp>_places_listed.sql
//
// Give a NEW migration file each time: one that has run on the live database is never rewritten.

import fs from "node:fs";

const out = process.argv[2];
if (!out) throw new Error("usage: node scripts/listed-places-sql.mjs <new migration file>");

const ts = fs.readFileSync("src/lib/listedPlaces.ts", "utf8");
const places = JSON.parse(ts.slice(ts.indexOf("= [") + 2, ts.lastIndexOf("]") + 1));

const q = (v) => (v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const arr = (xs) => `array[${xs.map(q).join(", ")}]`;

const placeRows = places.map(
  (p) => `    (${q(p.slug)}, ${q(p.name)}, ${arr(p.categories)}, 'listed', 'public', 'published', ${q(p.website)}, ${q(p.logo)}, now())`,
);
const locationRows = places.flatMap((p) =>
  p.locations.map((l, i) => `    (${q(p.slug)}, ${q(l.city)}, ${q(l.address)}, ${l.lat}, ${l.lng}, ${i + 1})`),
);

const sql = `-- The places map's Listed tier: ${places.length} pet businesses (${locationRows.length} addresses) from OpenStreetMap.
-- GENERATED by scripts/listed-places-sql.mjs from src/lib/listedPlaces.ts; the app shows that same list
-- until it can read these rows.
--
-- Facts only (name, what they do, address, an https website, the icon from their own site): these
-- businesses have not agreed to anything, so they are source 'public', tier 'listed', with no copy,
-- until they claim their page.
-- Data © OpenStreetMap contributors, available under the Open Database Licence (ODbL).
--
-- Needs 20261026180000_places.sql first. No email, no auth change; undone by
--   delete from public.places where source = 'public';

with p as (
  insert into public.places (slug, name, categories, tier, source, status, website_url, logo_path, published_at)
  values
${placeRows.join(",\n")}
  returning id, slug
)
insert into public.place_locations (place_id, city, address, lat, lng, sort_order)
select p.id, l.city, l.address, l.lat, l.lng, l.sort_order
from p
join (values
${locationRows.join(",\n")}
) as l(slug, city, address, lat, lng, sort_order) on l.slug = p.slug;
`;
fs.writeFileSync(out, sql);
console.log(`${places.length} places, ${locationRows.length} addresses → ${out}`);
